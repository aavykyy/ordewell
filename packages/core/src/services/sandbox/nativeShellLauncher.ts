import { chmodSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from 'fs';
import * as os from 'os';
import * as path from 'path';
import type { PlannerShellSandbox } from './plannerSandbox';
import type { SandboxLaunch } from './SandboxBackend';

/**
 * The launcher a harness's own shell runs through (ADR-0036 N2).
 *
 * Claude Code names one program in `CLAUDE_CODE_SHELL_PREFIX` and hands it the
 * whole command string as one argument, so the program is a script: its fixed
 * part is this session's sandbox launch, and its last argument is the command.
 * A harness that takes a shell instead (OpenCode's `shell`) can name the same
 * script the same way.
 */
export interface NativeShellLauncher {
  /** `CLAUDE_CODE_SHELL_PREFIX`: the script's path. */
  prefix: string;
  /**
   * `CLAUDE_CODE_TMPDIR`: a short per-session directory, writable in the
   * profile. Claude Code writes the shell's working directory there after
   * every command, and warns when the path passes about 30 bytes.
   */
  tmpdir: string;
  /** The harness settings `env` block that names both (N2). */
  env: Record<string, string>;
  /** Removes the script and its directory; the next process gets its own. */
  remove(): void;
}

/** The shell a command runs in: the user's own, `/bin/zsh` on the one platform N5 offers. */
export function nativeShellInvocation(platform: NodeJS.Platform, env: NodeJS.ProcessEnv = process.env): { shell: string; args: string[] } {
  const shell = platform === 'darwin' ? '/bin/zsh' : env.SHELL;
  return { shell: shell && path.posix.isAbsolute(shell) ? shell : '/bin/sh', args: ['-c'] };
}

/** Every launcher directory still on disk, removed when the process exits if its session never did. */
const live = new Set<string>();
let exitHook = false;

function keep(root: string): void {
  live.add(root);
  if (exitHook) return;
  exitHook = true;
  process.once('exit', () => {
    for (const dir of [...live]) rmSync(dir, { recursive: true, force: true });
  });
}

/**
 * One shell-quoted argument. The sandbox's paths and profile text are data:
 * they reach the script as single argv entries, never as shell syntax.
 */
function quoted(arg: string): string {
  return `'${arg.replace(/'/g, `'\\''`)}'`;
}

/**
 * The launcher's whole text: the profile and its paths as arguments, the
 * session environment `env -i` clears everything else, and the command the
 * harness appends as `$1`. Nothing the harness writes into its own end of the
 * command line can become the launcher's syntax.
 */
export function launcherScript(launch: SandboxLaunch): string {
  const env = Object.entries(launch.env)
    .filter((entry): entry is [string, string] => entry[1] !== undefined && /^[A-Za-z_][A-Za-z0-9_]*$/.test(entry[0]))
    .map(([name, value]) => quoted(`${name}=${value}`));
  return [
    '#!/bin/sh',
    '# Generated by Ordewell (ADR-0036 N2). The harness hands over the whole',
    '# command as one argument; the fixed part is the sealed profile for this session.',
    `exec /usr/bin/env -i ${[...env, quoted(launch.file), ...launch.args.map(quoted), '"$1"'].join(' ')}`,
    '',
  ].join('\n');
}

/**
 * Build the launcher for one planner process. The script lives in the OS's own
 * temporary directory, outside every directory the sealed profile can read or
 * write, so a command cannot rewrite what the next one starts through. Its
 * short temp folder is under `/tmp` instead, because the harness warns past
 * about thirty bytes and `/private/tmp` on macOS keeps the path short; the
 * profile is given only that folder, never the script.
 */
export async function createNativeShellLauncher(opts: {
  workspace: string;
  sandbox: PlannerShellSandbox;
  platform?: NodeJS.Platform;
  env?: NodeJS.ProcessEnv;
}): Promise<NativeShellLauncher> {
  const invocation = nativeShellInvocation(opts.platform ?? process.platform, opts.env);
  const root = realpathSync(mkdtempSync(path.join(os.tmpdir(), 'ordewell-native-shell-')));
  let shortTmp: string | null = null;
  try {
    shortTmp = realpathSync(mkdtempSync(path.join('/tmp', 'ow-')));
    const tmpdir = shortTmp;
    const launch = await opts.sandbox.launchNativeShell({
      workspace: opts.workspace,
      tmpdir,
      shell: invocation.shell,
      shellArgs: invocation.args,
      ...(opts.env ? { env: opts.env } : {}),
    });
    const prefix = path.join(root, 'run');
    writeFileSync(prefix, launcherScript(launch), { mode: 0o700 });
    chmodSync(prefix, 0o700);
    keep(root);
    keep(tmpdir);
    return {
      prefix,
      tmpdir,
      env: { CLAUDE_CODE_SHELL_PREFIX: prefix, CLAUDE_CODE_TMPDIR: tmpdir },
      remove: () => {
        for (const dir of [root, tmpdir]) {
          live.delete(dir);
          rmSync(dir, { recursive: true, force: true });
        }
      },
    };
  } catch (err) {
    for (const dir of [root, shortTmp].filter((dir): dir is string => dir !== null)) {
      live.delete(dir);
      rmSync(dir, { recursive: true, force: true });
    }
    throw err;
  }
}
